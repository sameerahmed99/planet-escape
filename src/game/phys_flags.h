#ifndef PHYS_FLAGS_INCLUDE
#define PHYS_FLAGS_INCLUDE

typedef struct PhysFlags {
  u64 v;
} PhysFlags;


const u64 PHYS_FLAG_LOCK_X_ROT=(1<<0);
const u64 PHYS_FLAG_LOCK_Y_ROT=(1<<1);
const u64 PHYS_FLAG_LOCK_Z_ROT=(1<<2);
const u64 PHYS_FLAG_LOCK_X_POS=(1<<3);
const u64 PHYS_FLAG_LOCK_Y_POS=(1<<4);
const u64 PHYS_FLAG_LOCK_Z_POS=(1<<5);
const u64 PHYS_FLAG_COL_DIR_TOP = (1<<6);
const u64 PHYS_FLAG_COL_DIR_BOTTOM = (1<<7);
const u64 PHYS_FLAG_COL_DIR_LEFT = (1<<8);
const u64 PHYS_FLAG_COL_DIR_RIGHT = (1<<9);


const u64 PHYS_FLAG_LOCK_ALL_ROT=PHYS_FLAG_LOCK_X_ROT | PHYS_FLAG_LOCK_Y_ROT | PHYS_FLAG_LOCK_Z_ROT;
const u64 PHYS_FLAG_LOCK_ALL_POS=PHYS_FLAG_LOCK_X_POS | PHYS_FLAG_LOCK_Y_POS | PHYS_FLAG_LOCK_Z_POS;

const u64 PHYS_FLAG_COL_DIR_ALL=PHYS_FLAG_COL_DIR_TOP | PHYS_FLAG_COL_DIR_BOTTOM | PHYS_FLAG_COL_DIR_LEFT | PHYS_FLAG_COL_DIR_RIGHT;



const u64 PHYS_FLAG_ALL_DEFAULT=PHYS_FLAG_COL_DIR_ALL;



#endif // PHYS_FLAGS_INCLUDE
